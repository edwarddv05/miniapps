// Bundles editor-web/editor.js (CodeMirror) into one HTML page and writes it
// to editor-html.ts, so the editor works offline inside a WebView.
// Run with `npm run build:editor` after changing editor-web/.

import { build } from 'esbuild';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const result = await build({
  entryPoints: [`${root}editor-web/editor.js`],
  bundle: true,
  minify: true,
  format: 'iife',
  target: 'safari16',
  write: false,
  legalComments: 'none',
});
const script = result.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');

const html = `<!doctype html><html><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1,maximum-scale=1,user-scalable=no,viewport-fit=cover">
<style>
html,body{margin:0;height:100%;overflow:hidden;-webkit-text-size-adjust:100%;-webkit-tap-highlight-color:transparent}
body{display:flex;flex-direction:column;box-sizing:border-box}
#editor{flex:1;min-height:0}
#keys{display:none;flex:none;gap:6px;padding:6px 8px;background:var(--bar);overflow-x:auto;-webkit-overflow-scrolling:touch;scrollbar-width:none}
#keys::-webkit-scrollbar{display:none}
body.typing #keys{display:flex}
#keys button{flex:none;min-width:40px;height:36px;padding:0 10px;border:0;border-radius:8px;background:var(--key);color:var(--key-text);font:500 15px ui-monospace,Menlo,monospace;box-shadow:0 1px 0 #0002}
#keys button:active{opacity:.6}
#keys .done{margin-left:auto;font:600 17px -apple-system,system-ui}
</style></head><body><div id="editor"></div><div id="keys"></div>
<script>${script}</script></body></html>`;

writeFileSync(`${root}editor-html.ts`, `// Generated by scripts/build-editor.mjs from editor-web/. Do not edit.\nexport const EDITOR_HTML = ${JSON.stringify(html)};\n`);
console.log(`editor-html.ts: ${(html.length / 1024).toFixed(0)} KB`);
